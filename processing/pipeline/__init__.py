"""v2 **조합(composition) 레이어** — 고정 뼈대 + 도메인 팩이 슬롯 전략을 고른다.

**흐름에서의 위치**: 파이프라인 뼈대와 도메인 사이에 놓인 층이다. 뼈대는 단계 **순서**만
고정하고, 각 단계에 무엇을 끼울지는 도메인 팩이 이름으로 선언한다.

**도메인을 코드로 분기하지 않는다**(헌법 4조). 도메인 차이는 *어떤 전략이 꽂혔는가*로만
드러나므로, 새 도메인 추가는 전략 등록 + 팩 정의로 끝나고 실행 경로는 손대지 않는다.
여기에 ``if 도메인 == …`` 이 하나라도 생기면 도메인이 늘 때마다 뼈대를 고치게 된다.

파일 맵
    - ``contracts.py``         : 각 슬롯에 끼울 함수의 **모양**(시그니처)만 선언.
    - ``registry.py``          : 슬롯·이름 → 구현 + 성질 태그.
    - ``builtins.py``          : 기본 전략 등록(**import 만으로 실행된다**).
    - ``packs.py``             : 도메인별 배선표 + 정책 이름.
    - ``policy.py``            : 배선이 그 도메인 규정에 맞는지 실행 전에 검사.
    - ``cross_types.py``       : 자산 사이 단계가 주고받는 타입.
    - ``cross_runner.py``      : 자산 사이 네 슬롯을 계약 순서대로 실행하는 공용 러너.
    - ``sample_strategies.py`` : 구조가 실제로 도는지 보여 주는 데모 전략.

⚠️ **부트스트랩**: 이 패키지는 아무것도 재수출하지 않는다. 다만 실행 진입점이
``builtins`` 를 import 하는 것만으로 기본 전략이 등록된다 — 안 쓰는 import 로 보여
지우면 팩이 전략 이름을 찾지 못해 터진다.
"""
